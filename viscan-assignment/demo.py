"""Scripted demo. Prints each request and response; also writes docs/sample_outputs.md"""
import json
from app.assistant import Assistant, Session
from app.llm import get_llm
from app.store import Store

a, s = Assistant(Store(), get_llm()), Session()
steps = [
    ("A. Retrieval (exact name, similar-name warning)", lambda: a.handle(s, "Open Priya Nair's latest OPG report")),
    ("A. Ambiguous patient (first name only)", lambda: a.handle(Session(), "Open Priya's latest OPG report")),
    ("A. Missing report", lambda: a.handle(Session(), "Show Rahul Mehta's CBCT")),
    ("C. Follow-up without naming the patient", lambda: a.handle(s, "Summarize her report")),
    ("B. Dictation -> structured draft", lambda: a.dictate(Session(), "Lower right third molar is horizontally impacted. Possible caries on upper left first molar. Patient is comfortable today.")),
]
md = ["# Sample outputs (generated by demo.py)\n"]
for title, fn in steps:
    out = json.dumps(fn(), indent=2, ensure_ascii=False)
    print(f"\n=== {title} ===\n{out}")
    md.append(f"## {title}\n```json\n{out}\n```\n")
open("docs/sample_outputs.md", "w").write("\n".join(md))
